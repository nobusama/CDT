"""
CDT Dataset Classes

Classes for dummy datasets and real datasets
"""

import random
import torch
from torch.utils.data import Dataset
from typing import Dict, List, Optional


class DummyCDTDataset(Dataset):
    """
    Dummy Dataset for CDT Training

    Generates a dummy dataset for contrastive learning.
    Generates multiple samples from each gene, treating samples
    from the same gene as positive pairs.

    Args:
        num_samples: Number of samples to generate
        samples_per_gene: Samples per gene (for contrastive learning)
        dna_length: DNA sequence length
        rna_length: RNA sequence length
        protein_length: Protein sequence length
        seed: Random seed

    Returns:
        dict: {
            'dna_sequence': str,
            'rna_sequence': str,
            'protein_sequence': str,
            'gene_id': int,  # For contrastive loss
            'sample_id': int
        }

    Example:
        >>> dataset = DummyCDTDataset(num_samples=1000, samples_per_gene=4)
        >>> sample = dataset[0]
        >>> print(sample['dna_sequence'])
        'ATGCGATCGATCG...'

    Note:
        - With samples_per_gene=4, generates 4 samples from each gene
        - Samples with the same gene_id form positive pairs
        - Used with InfoNCE loss
    """

    def __init__(
        self,
        num_samples: int = 1000,
        samples_per_gene: int = 4,
        dna_length: int = 100,
        rna_length: int = 80,
        protein_length: int = 30,
        seed: int = 42
    ):
        self.num_samples = num_samples
        self.samples_per_gene = samples_per_gene
        self.dna_length = dna_length
        self.rna_length = rna_length
        self.protein_length = protein_length

        # Number of unique genes
        self.num_genes = num_samples // samples_per_gene

        # Set random seed for reproducibility
        self.rng = random.Random(seed)

        # DNA/RNA/Protein alphabets
        self.dna_alphabet = ['A', 'T', 'G', 'C']
        self.rna_alphabet = ['A', 'U', 'G', 'C']
        self.protein_alphabet = list('ACDEFGHIKLMNPQRSTVWY')  # 20 amino acids

    def __len__(self) -> int:
        return self.num_samples

    def __getitem__(self, idx: int) -> Dict[str, any]:
        """
        Get a sample from the dataset

        Args:
            idx: Sample index

        Returns:
            dict: Sample dictionary containing sequences and metadata
        """
        # Assign gene_id based on sample grouping
        # Same gene_id = positive pair for contrastive learning
        gene_id = idx // self.samples_per_gene

        # Use deterministic random generation based on idx
        # This ensures same idx always returns same sequence
        local_rng = random.Random(self.rng.random() + idx)

        # Generate random sequences
        dna_sequence = self._generate_dna(local_rng)
        rna_sequence = self._generate_rna(local_rng)
        protein_sequence = self._generate_protein(local_rng)

        return {
            'dna_sequence': dna_sequence,
            'rna_sequence': rna_sequence,
            'protein_sequence': protein_sequence,
            'gene_id': gene_id,
            'sample_id': idx
        }

    def _generate_dna(self, rng: random.Random) -> str:
        """Generate random DNA sequence"""
        return ''.join(rng.choices(self.dna_alphabet, k=self.dna_length))

    def _generate_rna(self, rng: random.Random) -> str:
        """Generate random RNA sequence"""
        return ''.join(rng.choices(self.rna_alphabet, k=self.rna_length))

    def _generate_protein(self, rng: random.Random) -> str:
        """Generate random protein sequence"""
        return ''.join(rng.choices(self.protein_alphabet, k=self.protein_length))


class RealisticCDTDataset(Dataset):
    """
    Realistic CDT Dataset for Phase 5

    Loads biologically realistic synthetic data generated by
    realistic_data_generator.py

    Args:
        data_path: Path to JSON file with triplets
        split: 'train', 'val', or 'test' (not used for synthetic data)

    Example:
        >>> dataset = RealisticCDTDataset('data/phase5/synthetic_realistic_triplets.json')
        >>> sample = dataset[0]
        >>> print(sample['dna_sequence'])
    """

    def __init__(
        self,
        data_path: str,
        split: str = 'train'
    ):
        import json
        from pathlib import Path

        self.data_path = Path(data_path)
        self.split = split

        # Load data from JSON
        if not self.data_path.exists():
            raise FileNotFoundError(f"Data file not found: {self.data_path}")

        with open(self.data_path, 'r') as f:
            self.data = json.load(f)

        # Calculate number of unique genes
        self.num_genes = len(set(sample['gene_id'] for sample in self.data))

        print(f"Loaded {len(self.data)} samples from {self.data_path}")

    def __len__(self) -> int:
        return len(self.data)

    def __getitem__(self, idx: int) -> Dict[str, any]:
        """
        Get a sample from the dataset

        Returns:
            dict: {
                'dna_sequence': str,
                'rna_sequence': str,
                'protein_sequence': str,
                'gene_id': int,
                'sample_id': int,
                'gene_name': str,
                'annotations': dict,
                'codon_positions': List[Tuple[int, int, int]]  # NEW
            }
        """
        sample = self.data[idx]

        # Compute codon positions for alignment loss
        codon_positions = self._compute_codon_positions(
            sample['rna_sequence'],
            sample['protein_sequence'],
            sample['annotations'].get('coding_region', (0, len(sample['rna_sequence'])))
        )

        return {
            'dna_sequence': sample['dna_sequence'],
            'rna_sequence': sample['rna_sequence'],
            'protein_sequence': sample['protein_sequence'],
            'gene_id': sample['gene_id'],
            'sample_id': sample['sample_id'],
            'gene_name': sample['gene_name'],
            'variant_id': sample['variant_id'],
            'annotations': sample['annotations'],
            'codon_positions': codon_positions  # NEW
        }

    def _compute_codon_positions(
        self,
        rna_seq: str,
        protein_seq: str,
        coding_region: tuple
    ) -> List[tuple]:
        """
        Compute which RNA positions correspond to each amino acid

        Args:
            rna_seq: RNA sequence string
            protein_seq: Protein sequence string
            coding_region: (start, end) tuple for coding region

        Returns:
            List of (pos1, pos2, pos3) tuples, one per amino acid
            Each tuple contains the 3 RNA positions for the codon
        """
        start, end = coding_region
        positions = []

        for aa_idx in range(len(protein_seq)):
            codon_start = start + aa_idx * 3

            # Each amino acid corresponds to 3 consecutive RNA nucleotides
            pos1 = codon_start
            pos2 = codon_start + 1
            pos3 = codon_start + 2

            positions.append((pos1, pos2, pos3))

        return positions


def collate_fn(batch: List[Dict]) -> Dict[str, any]:
    """
    Custom collate function for DataLoader

    Since the CDT model performs tokenization internally,
    sequences are returned as lists without modification.

    Args:
        batch: List of samples from dataset

    Returns:
        dict: Batched data

    Example:
        >>> from torch.utils.data import DataLoader
        >>> dataset = DummyCDTDataset(num_samples=100)
        >>> loader = DataLoader(dataset, batch_size=16, collate_fn=collate_fn)
        >>> batch = next(iter(loader))
        >>> print(batch['dna_sequences'])  # List of 16 sequences
    """
    # Extract sequences as lists
    dna_sequences = [sample['dna_sequence'] for sample in batch]
    rna_sequences = [sample['rna_sequence'] for sample in batch]
    protein_sequences = [sample['protein_sequence'] for sample in batch]

    # Gene IDs as tensor for loss computation
    gene_ids = torch.tensor([sample['gene_id'] for sample in batch], dtype=torch.long)
    sample_ids = torch.tensor([sample['sample_id'] for sample in batch], dtype=torch.long)

    # Codon positions (if available in sample)
    codon_positions = None
    if 'codon_positions' in batch[0]:
        # Find max protein length in batch for padding
        max_protein_len = max(len(sample['protein_sequence']) for sample in batch)

        # Create padded tensor: (batch_size, max_protein_len, 3)
        codon_positions = torch.zeros(len(batch), max_protein_len, 3, dtype=torch.long)

        for i, sample in enumerate(batch):
            positions = sample['codon_positions']
            for j, (p1, p2, p3) in enumerate(positions):
                codon_positions[i, j] = torch.tensor([p1, p2, p3], dtype=torch.long)

    result = {
        'dna_sequences': dna_sequences,
        'rna_sequences': rna_sequences,
        'protein_sequences': protein_sequences,
        'gene_ids': gene_ids,
        'sample_ids': sample_ids
    }

    if codon_positions is not None:
        result['codon_positions'] = codon_positions

    return result


